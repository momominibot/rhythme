# Read current i18n.js
with open('i18n.js', 'r') as f:
    content = f.read()

# Find the DICT section and replace it
# The DICT starts after "var DICT = {" and ends before the closing "};"
dict_start = content.find('var DICT = {')
dict_end = content.find('\n  };', dict_start) + len('\n  };')

if dict_start == -1 or dict_end == -1:
    print("ERROR: Could not find DICT section")
    exit(1)

# Build new DICT content
new_dict = 'var DICT = {\n'

# zh section (keep existing - it's complete)
zh_match = re.search(r'zh:\s*\{(.*?)(?=\n\s+/\* ── Japanese|\n\s+ja:)', content, re.DOTALL)
if zh_match:
    new_dict += '    /* ── Chinese (zh) ── */\n'
    new_dict += '    zh: {' + zh_match.group(1) + '    },\n'

# Add ja, ms, es, de sections
lang_names = {'ja': 'Japanese', 'ms': 'Bahasa Melayu', 'es': 'Spanish', 'de': 'German'}
for lang in ['ja', 'ms', 'es', 'de']:
    new_dict += f'    /* ── {lang_names[lang]} ({lang}) ── */\n'
    new_dict += f'    {lang}: {{\n'
    items = TRANSLATIONS[lang]
    for i, (key, val) in enumerate(items.items()):
        # Escape single quotes in values
        val_escaped = val.replace("'", "\\'")
        comma = ',' if i < len(items) - 1 else ''
        new_dict += f"      '{key}': '{val_escaped}'{comma}\n"
    new_dict += '    },\n'

new_dict += '  };'

# Replace the DICT section
new_content = content[:dict_start] + new_dict + content[dict_end:]

# Update the comment at the top to include German
new_content = new_content.replace(
    'Currently supports: en, zh, ja, ms, es',
    'Currently supports: en, zh, ja, ms, es, de'
)

# Write the new file
with open('i18n.js', 'w') as f:
    f.write(new_content)

print(f"i18n.js updated successfully")
print(f"Languages: en, zh, ja, ms, es, de")
print(f"Keys per language:")
for lang in ['ja', 'ms', 'es', 'de']:
    print(f"  {lang}: {len(TRANSLATIONS[lang])} keys")
